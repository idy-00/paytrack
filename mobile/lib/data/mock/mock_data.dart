// 'paye' in schedule maps to SaleStatus.solde in Dart model
SaleStatus _s(String v) {
  if (v == 'paye') return SaleStatus.solde;
  return saleStatusFromString(v);
}

SaleScheduleItem _item(
  int num,
  String dueDate,
  int amount,
  String status, [
  String? paidDate,
]) => SaleScheduleItem(
      num: num,
      dueDate: dueDate,
      amount: amount,
      status: _s(status),
      paidDate: paidDate,
    );

